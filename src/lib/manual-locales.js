export function manualText(locale, text) {
	if (locale === 'en') return text;
	const index = ['zh-cn', 'ja', 'es', 'ko'].indexOf(locale);
	if (index < 0 || !STRINGS[text]?.[index]) throw new Error(`Missing manual translation: ${locale}: ${text}`);
	return STRINGS[text][index];
}
